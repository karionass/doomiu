// t('habits.of', { a: 1, b: 3 }) → "1 из 3". Если ключа нет — берём русский, потом сам ключ.
export const makeT = (lang) => (key, vars) => {
  const s = dict[lang]?.[key] ?? ru[key] ?? key;
  if (typeof s !== 'string' || !vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
};
